/// §15.6 — the frozen suite must pass with the system clock ten years forward. That is only
/// possible if every clock read routes through one injectable source.
- (void)testFixedClockIsStableAndDerivesSecondsFromMilliseconds {
    IRFixedClock *clock = [IRFixedClock clockAtUnixMilliseconds:1767830400123ULL];

    XCTAssertEqual([clock nowUnixMilliseconds], 1767830400123ULL);
    XCTAssertEqual([clock nowUnixSeconds], 1767830400ULL);
    XCTAssertEqual([clock nowUnixMilliseconds], 1767830400123ULL, @"a fixed clock must not drift");

    [clock advanceByMilliseconds:(uint64_t)kIRSkippedTTLMs];
    XCTAssertEqual([clock nowUnixMilliseconds], 1767830400123ULL + 604800000ULL);

    [clock advanceBySeconds:1];
    XCTAssertEqual([clock nowUnixMilliseconds], 1767830400123ULL + 604800000ULL + 1000ULL);

    /* Saturating rather than wrapping: a wrap would land the clock in 1970 and invert every
       comparison the test was written to check. */
    [clock advanceByMilliseconds:UINT64_MAX];
    XCTAssertEqual([clock nowUnixMilliseconds], UINT64_MAX);

    IRFixedClock *fromSeconds = [IRFixedClock clockAtUnixSeconds:1767830400ULL];
    XCTAssertEqual([fromSeconds nowUnixMilliseconds], 1767830400000ULL);
    XCTAssertEqual([fromSeconds nowUnixSeconds], 1767830400ULL);
}

/// The production clock is a real Unix wall clock, and its two readings agree.
- (void)testProductionClockIsAPlausibleUnixTime {
    id<IRClock> clock = [IREnvironment production].clock;

    const uint64_t seconds = [clock nowUnixSeconds];
    const uint64_t milliseconds = [clock nowUnixMilliseconds];

    XCTAssertGreaterThan(seconds, 1767225600ULL, @"clock must be past 2026-01-01");
    XCTAssertEqualWithAccuracy((double)(milliseconds / 1000ULL), (double)seconds, 2.0);
}

/// The production environment is a shared singleton, and its random source really produces
/// varying output (a smoke test against a stub that returns constants).
- (void)testProductionEnvironmentIsSharedAndRandom {
    XCTAssertEqual([IREnvironment production], [IREnvironment production]);

    NSError *error = nil;
    NSData *first = [self.provider randomBytesOfLength:32 error:&error];
    NSData *second = [self.provider randomBytesOfLength:32 error:&error];

    XCTAssertNotNil(first, @"%@", error);
    XCTAssertNotNil(second, @"%@", error);
