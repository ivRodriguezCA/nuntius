/// Verification MUST fail closed on a tampered signature, a tampered message, and the wrong key.
- (void)testEd25519VerificationRejectsTampering {
    NSError *error = nil;
    IREd25519Private *seed =
        [IREd25519Private fromData:[self dataFromHex:
            @"4ccd089b28ff96da9db6c346ec114e0f5b8a319f35aba624da8cf6ed4fb8a6fb"]
                           guarded:NO
                             error:&error];
    IREd25519Public *publicKey = [self.provider ed25519PublicKeyForSeed:seed error:&error];
    NSData *message = [self dataFromHex:@"72"];

    IREd25519Signature *signature = [self.provider ed25519SignMessage:message
                                                            withSeed:seed
                                                               error:&error];
    XCTAssertNotNil(signature);
    XCTAssertTrue([self.provider ed25519VerifySignature:signature
                                              ofMessage:message
                                              publicKey:publicKey]);

    NSMutableData *tamperedSignatureBytes = [signature.data mutableCopy];
    ((uint8_t *)tamperedSignatureBytes.mutableBytes)[0] ^= 0x01;
    IREd25519Signature *tamperedSignature = [IREd25519Signature fromData:tamperedSignatureBytes
                                                                   error:&error];

    XCTAssertFalse([self.provider ed25519VerifySignature:tamperedSignature
                                               ofMessage:message
                                               publicKey:publicKey]);
    XCTAssertFalse([self.provider ed25519VerifySignature:signature
                                               ofMessage:[self dataFromHex:@"73"]
                                               publicKey:publicKey]);

    IREd25519KeyPair *other = [self.provider generateEd25519KeyPairWithError:&error];
    XCTAssertFalse([self.provider ed25519VerifySignature:signature
                                               ofMessage:message
                                               publicKey:other.publicKey]);
}

