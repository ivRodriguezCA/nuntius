/**
 HKDF-SALT-EQUIV — `HKDF-Extract(Z32, ikm) == HKDF-Extract("", ikm)`.

 §3.2 states this explicitly and asks that it NOT be treated as a divergence point: HMAC pads any
 key shorter than its 64-byte block with zeros, so a 32-zero-byte salt and an empty salt are the
 same HMAC key. Everywhere the specification writes `salt = Z32` — §8.1's KDF_MK and §6.3's SK — an
 implementation MAY pass either. Recording it as an executable assertion is what stops a reviewer
 in another port from "fixing" it in one direction.
 */
- (void)testHKDFSaltEquivalence_Z32VersusEmpty {
    IRSecretBytes *ikm = [self secretFromHex:@"0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b"];
    IRSecretBytes *z32 = [[IRSecretBytes alloc] initWithBytes:kIRZ32 length:(NSUInteger)kIRLenZ32];

    NSError *error = nil;
    IRSecretBytes *withZ32 = [self.provider hkdfExtractWithSalt:z32 ikm:ikm error:&error];
    IRSecretBytes *withNil = [self.provider hkdfExtractWithSalt:nil ikm:ikm error:&error];

    XCTAssertNotNil(withZ32);
    XCTAssertNotNil(withNil);
    XCTAssertEqualObjects([self hexFromSecret:withZ32], [self hexFromSecret:withNil],
                          @"SPEC 3.2: Z32 and an empty salt MUST produce an identical PRK");

    /* And it really is the RFC 5869 A.3 PRK, so "they agree" is not two identical wrong answers. */
    XCTAssertEqualObjects([self hexFromSecret:withZ32],
                          @"19ef24a32c717b167f33a91d6f648bdf96596776afdb6377ac434c1c293ccb04");
}

/**
 HKDF-EXPAND-64 — the two-block T(i) counter loop that §7.2's KDF_RK needs.

 §3.2 names omitting the second block "the most common hand-rolled-HKDF bug", and §7.2 splits the
 64-byte output into RK' = okm[0..32) and CK = okm[32..64). A single-block implementation produces a
 correct-looking 32-byte RK' and a wrong (or absent) chain key — the failure would first surface as
 "the second message does not decrypt", far from its cause.

 Two assertions, and the second is the load-bearing one: the first 32 bytes of a 64-byte expansion
 MUST equal a 32-byte expansion (T(1) is shared), while the second 32 bytes MUST differ from the
 first (T(2) is genuinely computed, not a repeat of T(1)).
 */
- (void)testHKDFExpand64SpansTwoBlocks {
    IRSecretBytes *ikm = [self secretFromHex:@"0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b"];
    NSData *info = [NSData dataWithBytes:kIRLabelRK length:(NSUInteger)kIRLenLabelRK];

    NSError *error = nil;
    IRSecretBytes *prk = [self.provider hkdfExtractWithSalt:nil ikm:ikm error:&error];
    XCTAssertNotNil(prk, @"%@", error);

    IRSecretBytes *long64 = [self.provider hkdfExpandWithPRK:prk
                                                        info:info
                                                outputLength:(NSUInteger)kIRLenKDFRKOutput
                                                       error:&error];
    IRSecretBytes *short32 = [self.provider hkdfExpandWithPRK:prk
                                                         info:info
                                                 outputLength:(NSUInteger)kIRLenHMACSHA256
                                                        error:&error];

    XCTAssertNotNil(long64, @"%@", error);
    XCTAssertNotNil(short32, @"%@", error);
    XCTAssertEqual(long64.length, 64u);

    NSString *long64Hex = [self hexFromSecret:long64];
    NSString *firstBlock = [long64Hex substringToIndex:64];
    NSString *secondBlock = [long64Hex substringFromIndex:64];

    XCTAssertEqualObjects(firstBlock, [self hexFromSecret:short32],
                          @"T(1) must be identical whether L is 32 or 64");
    XCTAssertNotEqualObjects(firstBlock, secondBlock,
                             @"T(2) must be computed, not a repeat of T(1) - SPEC 3.2");
}

/// §3.2 — HKDF-Expand's ceiling is 255 blocks. Above it, fail rather than silently truncate.
- (void)testHKDFExpandRejectsOutOfRangeLengths {
    IRSecretBytes *ikm = [self secretFromHex:@"0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b"];

    NSError *error = nil;
    IRSecretBytes *prk = [self.provider hkdfExtractWithSalt:nil ikm:ikm error:&error];
    XCTAssertNotNil(prk);

    XCTAssertNil([self.provider hkdfExpandWithPRK:prk info:[NSData data] outputLength:0 error:NULL]);
    XCTAssertNil([self.provider hkdfExpandWithPRK:prk
                                             info:[NSData data]
                                     outputLength:(255 * 32) + 1
                                            error:NULL]);
    XCTAssertNotNil([self.provider hkdfExpandWithPRK:prk
                                                info:[NSData data]
                                        outputLength:(255 * 32)
                                               error:NULL]);
}

