}

#pragma mark - Randomness and the §13.1 tripwire

/**
 THE v3 DEFECT, AS AN EXECUTABLE TEST.

 A CSPRNG that FAILS must not leave a usable key behind. v3 wrote
 `__unused int result = SecRandomCopyBytes(...)` over an `NSMutableData dataWithLength:` buffer
 (IREncryptionService.m:476-481), and because -dataWithLength: zero-fills, an RNG failure produced
 an ALL-ZERO KEY with no signal at all — the canonical failing-open bug: everything works, both
 parties agree, and the session has no security whatsoever.
 */
- (void)testRNGFailurePropagatesRatherThanYieldingAZeroKey {
    IREnvironment *broken =
        [IREnvironment environmentWithRandomSource:[IRScriptedRandomSource failingSource]];

    NSError *error = nil;
    IRSodiumCryptoProvider *provider = [IRSodiumCryptoProvider providerWithEnvironment:broken
                                                                                 error:&error];
    XCTAssertNotNil(provider, @"%@", error);

    error = nil;
    XCTAssertNil([provider generateX25519KeyPairWithError:&error]);
    XCTAssertEqual(error.code, IRErrorRNGFailure);

    error = nil;
    XCTAssertNil([provider generateEd25519KeyPairWithError:&error]);
    XCTAssertEqual(error.code, IRErrorRNGFailure);

    error = nil;
    XCTAssertNil([provider randomNonceWithError:&error]);
    XCTAssertEqual(error.code, IRErrorRNGFailure);

    error = nil;
    XCTAssertNil([provider randomBytesOfLength:32 error:&error]);
    XCTAssertEqual(error.code, IRErrorRNGFailure);
}

/**
 THE SILENT BREAK — a CSPRNG that SUCCEEDS and returns zeros. No return-value check can catch it.

 §13.1: "Every freshly generated private key SHOULD additionally be checked with an all-zero test as
 a cheap tripwire before first use." This is what proves the tripwire is wired up.

 The X25519 case is the subtle one, and the assertion below is really about ORDERING. The §4.2 clamp
 sets `k[31] |= 0x40`, so an all-zero scalar becomes `00…0040` — NOT all-zero — the instant it is
 normalized. A tripwire applied after clamping can never fire. It has to run on the raw CSPRNG
 output, and it does.
 */
- (void)testAllZeroRNGOutputIsCaughtByTheTripwire {
    IREnvironment *silentlyBroken =
        [IREnvironment environmentWithRandomSource:[IRScriptedRandomSource zeroSource]];

    NSError *error = nil;
    IRSodiumCryptoProvider *provider = [IRSodiumCryptoProvider providerWithEnvironment:silentlyBroken
                                                                                 error:&error];
    XCTAssertNotNil(provider, @"%@", error);

    error = nil;
    XCTAssertNil([provider generateX25519KeyPairWithError:&error],
                 @"an all-zero scalar must be caught BEFORE the clamp masks it into 00..40");
    XCTAssertEqual(error.code, IRErrorRNGFailure);

    error = nil;
    XCTAssertNil([provider generateEd25519KeyPairWithError:&error]);
    XCTAssertEqual(error.code, IRErrorRNGFailure);
}

/// §15.5 rule 5 — a scripted source makes ephemeral keys and nonces reproducible, which is what
/// lets a frozen vector pin them. Exhaustion is a failure, never a wrap: cycling would hand the
/// same nonce to two AEAD calls under one key.
- (void)testScriptedRandomSourceIsDeterministicAndDoesNotWrap {
    NSData *script = [self dataFromHex:
        @"0102030405060708090a0b0c"
        @"a546e36bf0527c9d3b16154b82465edd62144c0ac1fc5a18506a2244ba449ac4"];

    IREnvironment *scripted =
        [IREnvironment environmentWithRandomSource:[IRScriptedRandomSource sourceWithData:script]];

    NSError *error = nil;
    IRSodiumCryptoProvider *provider = [IRSodiumCryptoProvider providerWithEnvironment:scripted
                                                                                 error:&error];

    IRNonce *nonce = [provider randomNonceWithError:&error];
    XCTAssertNotNil(nonce, @"%@", error);
    XCTAssertEqualObjects([nonce hexString], @"0102030405060708090a0b0c");

    IRX25519KeyPair *pair = [provider generateX25519KeyPairWithError:&error];
    XCTAssertNotNil(pair, @"%@", error);
    XCTAssertEqualObjects([self hexFromSecret:pair.privateKey],
                          @"a046e36bf0527c9d3b16154b82465edd62144c0ac1fc5a18506a2244ba449a44",
                          @"the scripted scalar, clamped per SPEC 4.2");

    error = nil;
    XCTAssertNil([provider randomNonceWithError:&error], @"the script is exhausted");
    XCTAssertEqual(error.code, IRErrorRNGFailure);
}

/// A generated X25519 private key is stored clamped (§4.2, §12.2 rule 8) and its public half is the
/// scalar's own base multiple.
- (void)testGeneratedX25519PrivateKeysAreClamped {
    for (NSUInteger attempt = 0; attempt < 16; attempt++) {
        NSError *error = nil;
        IRX25519KeyPair *pair = [self.provider generateX25519KeyPairWithError:&error];

        XCTAssertNotNil(pair, @"%@", error);
        XCTAssertTrue([IRX25519Private bytesAreClamped:pair.privateKey.constBytes],
