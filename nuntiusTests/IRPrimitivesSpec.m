/**
 LAYER 2 GATE — SPEC §3.2, §3.4, §4.4, §8.2, §13.1, §15.3.

 THE MOST IMPORTANT GATE IN THE PLAN, and the reason is structural rather than rhetorical: every
 test above this layer is SELF-CERTIFYING. A round-trip test passes when encrypt and decrypt are
 wrong in the same direction, which is exactly how v3 kept 23 green tests while X3DH silently
 collapsed to a single DH. The vectors below are EXTERNAL — published in RFC 5869, RFC 7748,
 RFC 8032 and RFC 8439 — so they cannot be satisfied by a self-consistent mistake.

 NOTHING DOWNSTREAM IS TRUSTWORTHY UNTIL THESE PASS. No protocol vector may be generated before
 this gate is green (§15.6 step 1), because a frozen vector generated by a subtly wrong primitive
 becomes normative for Java, Kotlin and Swift.

 Each test names the §15.3 vector id it will become when the generator runs at Layer 10.
 */
@interface IRPrimitivesSpec : XCTestCase
@property (nonatomic, strong) IRSodiumCryptoProvider *provider;
@end

@implementation IRPrimitivesSpec

- (void)setUp {
    [super setUp];

    XCTAssertTrue([IRSodium ensureInitialized:NULL], @"libsodium must initialize");

    NSError *error = nil;
    self.provider = [IRSodiumCryptoProvider productionProvider:&error];
    XCTAssertNotNil(self.provider, @"provider construction failed: %@", error);
    XCTAssertNil(error);
}

#pragma mark - Helpers

/// Hex -> NSData. Rejects odd lengths and non-hex digits by failing the test, so a typo in a
/// vector below surfaces as "bad vector" rather than as "primitive is broken".
- (NSData *)dataFromHex:(NSString *)hex {
    XCTAssertEqual(hex.length % 2, 0u, @"hex literal must have even length");

    NSMutableData *data = [NSMutableData dataWithCapacity:(hex.length / 2)];

    for (NSUInteger index = 0; index < hex.length; index += 2) {
        NSString *pair = [hex substringWithRange:NSMakeRange(index, 2)];
        NSScanner *scanner = [NSScanner scannerWithString:pair];
        unsigned int value = 0;

        XCTAssertTrue([scanner scanHexInt:&value], @"not hex: %@", pair);

        uint8_t byte = (uint8_t)value;
        [data appendBytes:&byte length:1];
    }

    return [data copy];
}

/// §15.5 rule 4 — all hex strings are lowercase, even length.
- (NSString *)hexFromData:(NSData *)data {
    const uint8_t *bytes = (const uint8_t *)data.bytes;
    NSMutableString *hex = [NSMutableString stringWithCapacity:(data.length * 2)];

    for (NSUInteger index = 0; index < data.length; index++) {
        [hex appendFormat:@"%02x", bytes[index]];
    }

    return [hex copy];
}

- (NSString *)hexFromSecret:(IRSecretBytes *)secret {
    return [self hexFromData:[NSData dataWithBytes:secret.constBytes length:secret.length]];
}

- (IRSecretBytes *)secretFromHex:(NSString *)hex {
    IRSecretBytes *secret = [[IRSecretBytes alloc] initWithData:[self dataFromHex:hex] guarded:NO];
    XCTAssertNotNil(secret);
    return secret;
}

- (IRX25519Private *)x25519PrivateFromHex:(NSString *)hex {
    NSError *error = nil;
    IRX25519Private *key = [IRX25519Private fromData:[self dataFromHex:hex] guarded:NO error:&error];
    XCTAssertNotNil(key, @"%@", error);
    return key;
}

- (IRX25519Public *)x25519PublicFromHex:(NSString *)hex {
    NSError *error = nil;
    IRX25519Public *key = [IRX25519Public fromData:[self dataFromHex:hex] error:&error];
    XCTAssertNotNil(key, @"%@", error);
    return key;
}

#pragma mark - RFC 5869 — HKDF-SHA256 (§3.2, vectors RFC5869-A1..A3)

/**
 RFC 5869 Appendix A.1 — basic case.

 §3.2: "Validate against the RFC 5869 Appendix A test vectors before running any protocol test."
 Extract, expand and the combined form are each checked, because §7.2's KDF_RK is a one-shot HKDF
 while the RFC publishes the intermediate PRK — a port that gets Extract right and Expand wrong
 fails only on the OKM.
 */
- (void)testRFC5869_A1 {
    IRSecretBytes *ikm = [self secretFromHex:@"0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b"];
    IRSecretBytes *salt = [self secretFromHex:@"000102030405060708090a0b0c"];
    NSData *info = [self dataFromHex:@"f0f1f2f3f4f5f6f7f8f9"];

    NSError *error = nil;
    IRSecretBytes *prk = [self.provider hkdfExtractWithSalt:salt ikm:ikm error:&error];

    XCTAssertNotNil(prk, @"%@", error);
    XCTAssertEqualObjects([self hexFromSecret:prk],
                          @"077709362c2e32df0ddc3f0dc47bba6390b6c73bb50f9c3122ec844ad7c2b3e5");

    IRSecretBytes *okm = [self.provider hkdfExpandWithPRK:prk info:info outputLength:42 error:&error];

    XCTAssertNotNil(okm, @"%@", error);
    XCTAssertEqualObjects([self hexFromSecret:okm],
                          @"3cb25f25faacd57a90434f64d0362f2a2d2d0a90cf1a5a4c5db02d56ecc4c5bf"
                          @"34007208d5b887185865");

    IRSecretBytes *combined = [self.provider hkdfWithSalt:salt
                                                     ikm:ikm
                                                    info:info
                                            outputLength:42
                                                   error:&error];

    XCTAssertNotNil(combined, @"%@", error);
    XCTAssertEqualObjects([self hexFromSecret:combined], [self hexFromSecret:okm],
                          @"HKDF(salt,ikm,info,L) must equal Expand(Extract(salt,ikm),info,L)");
}

