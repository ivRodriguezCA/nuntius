#pragma mark - RFC 8439 — ChaCha20-Poly1305 IETF (§8.2, vector RFC8439-AEAD)

/**
 RFC 8439 §2.8.2, the published AEAD example.

 The 12-byte nonce pins the IETF construction: the non-IETF libsodium spelling takes 8 bytes and is
 a silent incompatibility (§3.3), and this vector is what makes picking it up by autocomplete a
 test failure rather than a field incident. The 16-byte Poly1305 tag is APPENDED, so the sealed
 output is `ciphertext ‖ tag` and `len(sealed) == len(pt) + 16` exactly (§8.2 — ChaCha20 is a stream
 cipher; there is no padding).
 */
- (void)testRFC8439_AEADSealAndOpen {
    NSData *plaintext = [self dataFromHex:
        @"4c616469657320616e642047656e746c656d656e206f662074686520636c6173"
        @"73206f66202739393a204966204920636f756c64206f6666657220796f75206f"
        @"6e6c79206f6e652074697020666f7220746865206675747572652c2073756e73"
        @"637265656e20776f756c642062652069742e"];
    NSData *associatedData = [self dataFromHex:@"50515253c0c1c2c3c4c5c6c7"];

    NSError *error = nil;
    IRMessageEncKey *key = [IRMessageEncKey fromData:[self dataFromHex:
        @"808182838485868788898a8b8c8d8e8f909192939495969798999a9b9c9d9e9f"]
                                             guarded:NO
                                               error:&error];
    IRNonce *nonce = [IRNonce fromData:[self dataFromHex:@"070000004041424344454647"] error:&error];

    XCTAssertNotNil(key, @"%@", error);
    XCTAssertNotNil(nonce, @"%@", error);

    NSData *sealed = [self.provider aeadSealPlaintext:plaintext
                                                  key:key
                                                nonce:nonce
                                       associatedData:associatedData
                                                error:&error];

    XCTAssertNotNil(sealed, @"%@", error);
    XCTAssertEqual(sealed.length, plaintext.length + (NSUInteger)kIRLenAEADTag);
    XCTAssertEqualObjects([self hexFromData:sealed],
                          @"d31a8d34648e60db7b86afbc53ef7ec2a4aded51296e08fea9e2b5a736ee62d6"
                          @"3dbea45e8ca9671282fafb69da92728b1a71de0a9e060b2905d6a5b67ecd3b36"
                          @"92ddbd7f2d778b8c9803aee328091b58fab324e4fad675945585808b4831d7bc"
                          @"3ff4def08e4b7a9de576d26586cec64b6116"
                          @"1ae10b594f09e26a7e902ecbd0600691",
                          @"RFC 8439 2.8.2 ciphertext with the 16-byte tag appended");

    NSData *opened = [self.provider aeadOpenCiphertextAndTag:sealed
                                                         key:key
                                                       nonce:nonce
                                              associatedData:associatedData
                                                       error:&error];

    XCTAssertNotNil(opened, @"%@", error);
    XCTAssertEqualObjects(opened, plaintext);
}

/**
 Every tamper is ERR_AEAD_AUTH_FAILED, including a single flipped bit of ASSOCIATED DATA.

 That last case is what §8.5 buys: AD is `SESSION_AD ‖ the complete header`, so the version byte,
 the type byte and the flags are CRYPTOGRAPHICALLY ENFORCED rather than checked by an `if`. A
 tampered version byte is an authentication failure — a strictly stronger fix for defect 13 than
 adding validation code, and it comes free with the AEAD.
 */
- (void)testAEADRejectsEveryTamper {
    NSData *plaintext = [@"nuntius v4" dataUsingEncoding:NSUTF8StringEncoding];
    NSData *associatedData = [self dataFromHex:@"04010000"];

    NSError *error = nil;
    IRMessageEncKey *key = [IRMessageEncKey fromData:[self dataFromHex:
        @"808182838485868788898a8b8c8d8e8f909192939495969798999a9b9c9d9e9f"]
                                             guarded:NO
                                               error:&error];
    IRNonce *nonce = [self.provider randomNonceWithError:&error];
    XCTAssertNotNil(nonce, @"%@", error);

    NSData *sealed = [self.provider aeadSealPlaintext:plaintext
                                                  key:key
                                                nonce:nonce
                                       associatedData:associatedData
                                                error:&error];
    XCTAssertNotNil(sealed, @"%@", error);

    // 1. A flipped ciphertext bit.
    NSMutableData *tamperedCiphertext = [sealed mutableCopy];
    ((uint8_t *)tamperedCiphertext.mutableBytes)[0] ^= 0x01;
    error = nil;
    XCTAssertNil([self.provider aeadOpenCiphertextAndTag:tamperedCiphertext
                                                     key:key
                                                   nonce:nonce
                                          associatedData:associatedData
                                                   error:&error]);
    XCTAssertEqual(error.code, IRErrorAEADAuthFailed);

    // 2. A flipped TAG bit.
    NSMutableData *tamperedTag = [sealed mutableCopy];
    ((uint8_t *)tamperedTag.mutableBytes)[sealed.length - 1] ^= 0x01;
    error = nil;
    XCTAssertNil([self.provider aeadOpenCiphertextAndTag:tamperedTag
                                                     key:key
                                                   nonce:nonce
                                          associatedData:associatedData
                                                   error:&error]);
    XCTAssertEqual(error.code, IRErrorAEADAuthFailed);

    // 3. A flipped ASSOCIATED DATA bit - here, the protocol version byte.
    error = nil;
    XCTAssertNil([self.provider aeadOpenCiphertextAndTag:sealed
                                                     key:key
                                                   nonce:nonce
                                          associatedData:[self dataFromHex:@"03010000"]
                                                   error:&error]);
    XCTAssertEqual(error.code, IRErrorAEADAuthFailed);

    // 4. The wrong nonce.
    error = nil;
    XCTAssertNil([self.provider aeadOpenCiphertextAndTag:sealed
                                                     key:key
                                                   nonce:[self.provider randomNonceWithError:NULL]
                                          associatedData:associatedData
                                                   error:&error]);
    XCTAssertEqual(error.code, IRErrorAEADAuthFailed);

    // 5. The wrong key.
    IRMessageEncKey *wrongKey = [IRMessageEncKey fromData:[self dataFromHex:
        @"00112233445566778899aabbccddeeff00112233445566778899aabbccddeeff"]
                                                  guarded:NO
                                                    error:NULL];
    error = nil;
    XCTAssertNil([self.provider aeadOpenCiphertextAndTag:sealed
                                                     key:wrongKey
                                                   nonce:nonce
                                          associatedData:associatedData
                                                   error:&error]);
    XCTAssertEqual(error.code, IRErrorAEADAuthFailed);

    // 6. Truncated below the tag width. Unreachable through the §10 gates, which guarantee at least
    //    HDR_LEN + 16 bytes, but reachable through §12.3's at-rest seal, which no gate covers.
    error = nil;
    XCTAssertNil([self.provider aeadOpenCiphertextAndTag:[sealed subdataWithRange:NSMakeRange(0, 8)]
                                                     key:key
                                                   nonce:nonce
                                          associatedData:associatedData
                                                   error:&error]);
    XCTAssertEqual(error.code, IRErrorAEADAuthFailed);
}

